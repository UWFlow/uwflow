export const validateEmail = (email: string): boolean => {
  const re =
    /^(([^<>()[\]\\.,;:\s@"]+(\.[^<>()[\]\\.,;:\s@"]+)*)|(".+"))@((\[[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\])|(([a-zA-Z\-0-9]+\.)+[a-zA-Z]{2,}))$/;
  return re.test(email.toLowerCase());
};

export const SIGNUP_EMAIL_DOMAIN = 'uwaterloo.ca';

export const isSignupEmailAllowed = (email: string): boolean =>
  email.trim().toLowerCase().endsWith(`@${SIGNUP_EMAIL_DOMAIN}`);
